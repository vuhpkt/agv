#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
AGV STM32 - IR Sensor Array Desk Calibration Tool
Connects to OpenOCD RTT Server (localhost:9090), reads raw ADC telemetry
while the user swipes white paper and black tape across the 5 IR sensors,
validates sensor dynamic range, and generates Application/Inc/app_line_calib_defaults.h.

Build and Flash are intentionally left to the user after reviewing the values.
"""

import argparse
import datetime
import json
import os
import re
import socket
import sys
import time

LINE_DATA_PATTERN = re.compile(
    r"^DATA:LINE,(\d+),(\d+),(\d+),(\d+),(\d+),(\d+),(\d+),(\d+),(\d+),(\d+),(\d+),(-?\d+),(\d+)"
)

SENSOR_NAMES = ["IR_R2 (Ch0)", "IR_R1 (Ch1)", "IR_MID(Ch2)", "IR_L1 (Ch3)", "IR_L2 (Ch4)"]


class CalibrationStats:
    """Tracks running min and max raw ADC values across all sensors."""

    def __init__(self, num_sensors=5):
        self.num_sensors = num_sensors
        self.min_raw = [4095] * num_sensors
        self.max_raw = [0] * num_sensors
        self.sample_count = 0

    def update(self, raw_values):
        if len(raw_values) != self.num_sensors:
            return
        for i in range(self.num_sensors):
            val = raw_values[i]
            if val < self.min_raw[i]:
                self.min_raw[i] = val
            if val > self.max_raw[i]:
                self.max_raw[i] = val
        self.sample_count += 1


def parse_line_telemetry(line):
    """
    Extracts 5 raw ADC values from DATA:LINE telemetry line.
    Returns list of 5 ints if matched, else None.
    """
    m = LINE_DATA_PATTERN.match(line.strip())
    if not m:
        return None
    return [int(m.group(i)) for i in range(2, 7)]


def validate_calibration(min_raw, max_raw, min_dynamic_range=100):
    """
    Validates optical calibration values:
    - Min must be strictly less than Max.
    - Dynamic range (Max - Min) must be >= min_dynamic_range.
    Returns (is_valid: bool, errors: list of str).
    """
    errors = []
    num_sensors = min(len(min_raw), len(max_raw))

    for i in range(num_sensors):
        name = SENSOR_NAMES[i] if i < len(SENSOR_NAMES) else f"Sensor {i}"
        mn = min_raw[i]
        mx = max_raw[i]
        delta = mx - mn

        if mn < 0 or mx > 4095:
            errors.append(f"{name}: ADC reading out of range [0..4095] (min={mn}, max={mx})")
        elif mn >= mx:
            errors.append(f"{name}: Min ADC ({mn}) >= Max ADC ({mx})")
        elif delta < min_dynamic_range:
            errors.append(f"{name}: Dynamic range too low ({delta} < {min_dynamic_range} ADC units)")

    return len(errors) == 0, errors


def generate_header_content(min_raw, max_raw):
    """Generates the C header file content with the calibrated arrays."""
    timestamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    min_str = ", ".join(str(v) for v in min_raw)
    max_str = ", ".join(str(v) for v in max_raw)

    return f"""/**
 * @file app_line_calib_defaults.h
 * @brief Default optical calibration parameters for 5-sensor IR array
 *
 * Auto-generated by scripts/calibrate_line.py on {timestamp}
 * Values represent ADC readings for white background (min) and black line (max).
 */

#ifndef APP_LINE_CALIB_DEFAULTS_H
#define APP_LINE_CALIB_DEFAULTS_H

#include <stdint.h>

/**
 * @brief Calibrated raw ADC thresholds for 5 IR channels [R2, R1, MID, L1, L2]
 */
#define APP_LINE_CALIB_MIN_RAW   {{ {min_str} }}
#define APP_LINE_CALIB_MAX_RAW   {{ {max_str} }}

#endif /* APP_LINE_CALIB_DEFAULTS_H */
"""


def save_calib_json(min_raw, max_raw, file_path):
    """Saves calibration values and metadata to JSON file."""
    os.makedirs(os.path.dirname(os.path.abspath(file_path)), exist_ok=True)
    payload = {
        "timestamp": datetime.datetime.now().isoformat(),
        "num_sensors": len(min_raw),
        "min_raw": min_raw,
        "max_raw": max_raw,
        "delta": [max_raw[i] - min_raw[i] for i in range(len(min_raw))],
    }
    with open(file_path, "w", encoding="utf-8") as f:
        json.dump(payload, f, indent=2)


def load_calib_json(file_path):
    """Loads calibration values from JSON file. Returns (min_raw, max_raw)."""
    with open(file_path, "r", encoding="utf-8") as f:
        data = json.load(f)
    return data["min_raw"], data["max_raw"]


def write_calib_header(min_raw, max_raw, header_path):
    """Writes the generated C header content to the specified path."""
    os.makedirs(os.path.dirname(os.path.abspath(header_path)), exist_ok=True)
    content = generate_header_content(min_raw, max_raw)
    with open(header_path, "w", encoding="utf-8") as f:
        f.write(content)


def print_calibration_table(min_raw, max_raw, min_dynamic_range=100):
    """Prints a formatted report table of the calibration results."""
    print("\n" + "=" * 68)
    print("           AGV STM32 - IR ARRAY CALIBRATION REPORT")
    print("=" * 68)
    print(f"{'Channel':<15} | {'Min (White)':>12} | {'Max (Black)':>12} | {'Delta':>8} | {'Status':<10}")
    print("-" * 68)

    all_passed = True
    for i in range(len(min_raw)):
        name = SENSOR_NAMES[i] if i < len(SENSOR_NAMES) else f"Ch {i}"
        mn = min_raw[i]
        mx = max_raw[i]
        delta = mx - mn
        status = "PASS" if delta >= min_dynamic_range and mn < mx else "FAIL"
        if status == "FAIL":
            all_passed = False
        print(f"{name:<15} | {mn:>12d} | {mx:>12d} | {delta:>8d} | {status:<10}")

    print("=" * 68)
    if all_passed:
        print("  [SUCCESS] All 5 IR sensors passed dynamic range validation (>= 100).")
    else:
        print("  [WARNING] One or more sensors failed validation. Check sensor wiring/height.")
    print("=" * 68 + "\n")
    return all_passed


def run_calibration(host="localhost", port=9090, duration_ms=5000, save=True, header_path=None, json_path=None):
    """Runs the live calibration routine over RTT socket."""
    repo_root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    if header_path is None:
        header_path = os.path.join(repo_root, "Application", "Inc", "app_line_calib_defaults.h")
    if json_path is None:
        json_path = os.path.join(repo_root, "scripts", "line_calib.json")

    print(f"[+] Connecting to OpenOCD RTT Server at {host}:{port}...")
    try:
        s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        s.settimeout(3.0)
        s.connect((host, port))
        print("[+] Connected to STM32 RTT Server!")
    except Exception as e:
        print(f"[-] Connection failed: {e}")
        print("    -> Make sure OpenOCD RTT Server is running: ./rtt.sh")
        return False

    cmd = f"LINE_TEST SENSOR {duration_ms} 0\n"
    print(f"[+] Sending command: {cmd.strip()}")
    s.sendall(cmd.encode("utf-8"))

    print("\n" + "*" * 60)
    print(f"  [ACTION REQUIRED] SWIPE SENSORS OVER PAPER & TAPE NOW!")
    print(f"  Gently swipe white paper and black tape across all 5 sensors.")
    print(f"  Calibration window: {duration_ms / 1000.0:.1f} seconds...")
    print("*" * 60 + "\n")

    stats = CalibrationStats(num_sensors=5)
    buffer = ""
    start_time = time.time()
    last_ui_update = 0

    try:
        while True:
            try:
                data = s.recv(1024).decode("utf-8", errors="ignore")
            except socket.timeout:
                if (time.time() - start_time) * 1000 > duration_ms + 2000:
                    break
                continue

            if not data:
                break

            buffer += data
            lines = buffer.split("\r\n")
            buffer = lines.pop()

            for line in lines:
                line = line.strip()
                if not line:
                    continue

                raw = parse_line_telemetry(line)
                if raw:
                    stats.update(raw)
                    now = time.time()
                    if now - last_ui_update > 0.15:
                        last_ui_update = now
                        elapsed = int((now - start_time) * 1000)
                        sys.stdout.write(
                            f"\r[Scanning... {elapsed:5d}ms / {duration_ms}ms] Samples: {stats.sample_count:4d} | Raw: {raw}"
                        )
                        sys.stdout.flush()

                if "DATA_END" in line:
                    break

            if "DATA_END" in buffer or (time.time() - start_time) * 1000 > duration_ms + 2500:
                break

    except KeyboardInterrupt:
        print("\n[!] Calibration interrupted by user.")
        try:
            s.sendall(b"LINE_TEST STOP\n")
        except Exception:
            pass
    finally:
        s.close()

    print("\n\n[+] Data collection complete! Total samples: ", stats.sample_count)
    if stats.sample_count < 10:
        print("[-] Error: Insufficient samples collected. Did the STM32 receive the command?")
        return False

    all_passed = print_calibration_table(stats.min_raw, stats.max_raw)

    if save:
        save_calib_json(stats.min_raw, stats.max_raw, json_path)
        print(f"[+] Calibration saved to JSON: {json_path}")

        write_calib_header(stats.min_raw, stats.max_raw, header_path)
        print(f"[+] C Header updated successfully: {header_path}")

        print("\n" + "-" * 68)
        print("  NEXT STEPS (BUILD & FLASH):")
        print("  1. Verify the constants in: Application/Inc/app_line_calib_defaults.h")
        print("  2. Compile firmware:       ./build.sh (or cmake --build build/Debug)")
        print("  3. Flash firmware to STM32: ./flash.sh (or cmake --build build/Debug -t flash)")
        print("  4. Disconnect ST-Link, place AGV on floor track and power on.")
        print("-" * 68 + "\n")

    return all_passed


def main():
    parser = argparse.ArgumentParser(description="AGV STM32 IR Array Desk Calibration Tool")
    parser.add_argument("--scan", type=int, default=5000, help="Scan duration in ms (default: 5000)")
    parser.add_argument("--host", type=str, default="localhost", help="RTT host (default: localhost)")
    parser.add_argument("--port", type=int, default=9090, help="RTT port (default: 9090)")
    parser.add_argument("--no-save", action="store_true", help="Do not save JSON or update C header")
    parser.add_argument("--load", type=str, default="", help="Load previous JSON file and update C header")
    args = parser.parse_args()

    repo_root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    header_path = os.path.join(repo_root, "Application", "Inc", "app_line_calib_defaults.h")
    json_path = os.path.join(repo_root, "scripts", "line_calib.json")

    if args.load:
        target_json = args.load if os.path.isfile(args.load) else json_path
        print(f"[+] Loading calibration from {target_json}...")
        min_raw, max_raw = load_calib_json(target_json)
        print_calibration_table(min_raw, max_raw)
        write_calib_header(min_raw, max_raw, header_path)
        print(f"[+] C Header updated: {header_path}")
        return

    run_calibration(
        host=args.host,
        port=args.port,
        duration_ms=args.scan,
        save=(not args.no_save),
        header_path=header_path,
        json_path=json_path,
    )


if __name__ == "__main__":
    main()
